﻿using UnityEngine;
using UnityEngine.Serialization;

namespace RealPhysicsPlacer
{
    /// <summary>
    /// Records the method used to generate a baked collider set.
    /// </summary>
    public enum RealPhysicsPlacerBakedColliderShape
    {
        Box = 0,
        ConvexHull = 1,
        MultiHull = 2,
        RealHulls = 5
    }

    /// <summary>
    /// Quality target used by the built-in Real Hulls collider solver.
    /// </summary>
    public enum RealPhysicsPlacerRealHullsQuality
    {
        Fast,
        Balanced,
        Accurate,
        Maximum
    }

    /// <summary>
    /// Marker component for collider sets generated by the RealTransforms baker.
    /// It stores bake settings for review and draws optional editor gizmos for the generated colliders.
    /// </summary>
    [DisallowMultipleComponent]
    public sealed class RealPhysicsPlacerBakedCollider : MonoBehaviour
    {
        [Tooltip("Draw generated collider outlines in the Scene view.")]
        public bool drawGizmos = true;
        [Tooltip("Draw collider gizmos even when this object is not selected.")]
        public bool drawWhenUnselected = true;
        [Tooltip("Draw a faint filled preview in addition to wire outlines.")]
        public bool drawSolidGizmos;
        [Tooltip("Scene-view color used for generated collider gizmos.")]
        public Color gizmoColor = new Color(1f, 0.55f, 0.08f, 0.85f);
        public RealPhysicsPlacerBakedColliderShape shape = RealPhysicsPlacerBakedColliderShape.RealHulls;
        public int maxHulls = 32;
        public int maxHullVertices = 96;
        public RealPhysicsPlacerRealHullsQuality realHullsQuality = RealPhysicsPlacerRealHullsQuality.Balanced;
        public int realHullsVoxelResolution = 48;
        public int realHullsSurfaceSamples = 10000;
        public int realHullsMaxSplitCandidates = 64;
        public float realHullsShapeAccuracy = 0.04f;
        public bool realHullsMergePass = true;
        public bool mergeSmallHulls = true;
        public int smallHullMergeTriangleLimit = 255;
        public float smallHullMergeExpansion = 1.35f;
        public float concavityThreshold = 0.035f;
        [HideInInspector] public bool splitComponents;
        [HideInInspector]
        public int directHullTriangles = 96;
        [FormerlySerializedAs("hullShrink")]
        public float hullPadding;
        public int hullCount;
        public string sourceMeshName = string.Empty;
        public string sourceMeshHash = string.Empty;
        public string assetPath = string.Empty;

        private void OnDrawGizmos()
        {
            if (drawWhenUnselected)
            {
                DrawColliderGizmos();
            }
        }

        private void OnDrawGizmosSelected()
        {
            if (!drawWhenUnselected)
            {
                DrawColliderGizmos();
            }
        }

        private void DrawColliderGizmos()
        {
            if (!drawGizmos || !enabled)
            {
                return;
            }

            var previousColor = Gizmos.color;
            var previousMatrix = Gizmos.matrix;
            var solidColor = new Color(gizmoColor.r, gizmoColor.g, gizmoColor.b, Mathf.Clamp01(gizmoColor.a * 0.14f));
            foreach (var meshCollider in GetComponentsInChildren<MeshCollider>(true))
            {
                if (meshCollider == null || meshCollider.sharedMesh == null)
                {
                    continue;
                }

                var usableForDynamicPhysics = meshCollider.enabled && meshCollider.convex;
                var wireColor = usableForDynamicPhysics
                    ? gizmoColor
                    : new Color(1f, 0.2f, 0.08f, Mathf.Clamp01(gizmoColor.a));
                Gizmos.matrix = meshCollider.transform.localToWorldMatrix;
                if (drawSolidGizmos)
                {
                    Gizmos.color = usableForDynamicPhysics
                        ? solidColor
                        : new Color(1f, 0.2f, 0.08f, Mathf.Clamp01(gizmoColor.a * 0.08f));
                    Gizmos.DrawMesh(meshCollider.sharedMesh);
                }

                Gizmos.color = wireColor;
                Gizmos.DrawWireMesh(meshCollider.sharedMesh);
            }

            foreach (var boxCollider in GetComponentsInChildren<BoxCollider>(true))
            {
                if (boxCollider == null)
                {
                    continue;
                }

                Gizmos.matrix = boxCollider.transform.localToWorldMatrix * Matrix4x4.Translate(boxCollider.center);
                if (drawSolidGizmos)
                {
                    Gizmos.color = solidColor;
                    Gizmos.DrawCube(Vector3.zero, boxCollider.size);
                }

                Gizmos.color = gizmoColor;
                Gizmos.DrawWireCube(Vector3.zero, boxCollider.size);
            }

            foreach (var sphereCollider in GetComponentsInChildren<SphereCollider>(true))
            {
                if (sphereCollider == null)
                {
                    continue;
                }

                Gizmos.matrix = sphereCollider.transform.localToWorldMatrix * Matrix4x4.Translate(sphereCollider.center);
                if (drawSolidGizmos)
                {
                    Gizmos.color = solidColor;
                    Gizmos.DrawSphere(Vector3.zero, sphereCollider.radius);
                }

                Gizmos.color = gizmoColor;
                Gizmos.DrawWireSphere(Vector3.zero, sphereCollider.radius);
            }

            foreach (var capsuleCollider in GetComponentsInChildren<CapsuleCollider>(true))
            {
                if (capsuleCollider == null)
                {
                    continue;
                }

                Gizmos.matrix = capsuleCollider.transform.localToWorldMatrix * Matrix4x4.Translate(capsuleCollider.center);
                DrawCapsuleGizmo(capsuleCollider, solidColor);
            }

            Gizmos.matrix = previousMatrix;
            Gizmos.color = previousColor;
        }

        private void DrawCapsuleGizmo(CapsuleCollider capsuleCollider, Color solidColor)
        {
            var radius = Mathf.Max(0f, capsuleCollider.radius);
            var height = Mathf.Max(radius * 2f, capsuleCollider.height);
            var axis = capsuleCollider.direction == 0
                ? Vector3.right
                : capsuleCollider.direction == 2 ? Vector3.forward : Vector3.up;
            var centerOffset = Mathf.Max(0f, height * 0.5f - radius);
            var a = axis * centerOffset;
            var b = -axis * centerOffset;
            if (drawSolidGizmos)
            {
                Gizmos.color = solidColor;
                Gizmos.DrawSphere(a, radius);
                Gizmos.DrawSphere(b, radius);
            }

            Gizmos.color = gizmoColor;
            Gizmos.DrawWireSphere(a, radius);
            Gizmos.DrawWireSphere(b, radius);
            var sideA = capsuleCollider.direction == 0 ? Vector3.up : Vector3.right;
            var sideB = capsuleCollider.direction == 2 ? Vector3.up : Vector3.forward;
            Gizmos.DrawLine(a + sideA * radius, b + sideA * radius);
            Gizmos.DrawLine(a - sideA * radius, b - sideA * radius);
            Gizmos.DrawLine(a + sideB * radius, b + sideB * radius);
            Gizmos.DrawLine(a - sideB * radius, b - sideB * radius);
        }
    }
}
